using Microsoft.AspNetCore.Http.HttpResults;

using SignalSafe.Api.Contracts;
using SignalSafe.Core.ControlTables;
using SignalSafe.Core.Domain;
using SignalSafe.Core.Layouts;
using SignalSafe.Core.Routing;
using SignalSafe.Core.Rules;
using SignalSafe.Excel;

namespace SignalSafe.Api.Endpoints;

public static class CheckEndpoints
{
    public const long MaxLayoutBytes = 2 * 1024 * 1024;
    public const long MaxTablesBytes = 10 * 1024 * 1024;
    private const string XlsxType = "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

    public static void MapCheckEndpoints(this IEndpointRouteBuilder app)
    {
        var api = app.MapGroup("/api/v1").WithTags("SignalSafe");

        api.MapGet("/samples", () => Samples.All.Select(s => new { s.Id, s.Name, s.Description }))
            .WithSummary("List the built-in sample layouts");

        api.MapGet("/samples/{id}/check", Results<Ok<CheckResult>, NotFound<ProblemDetailsMessage>> (string id) =>
            {
                var sample = Samples.Find(id);
                if (sample is null)
                    return TypedResults.NotFound(new ProblemDetailsMessage($"There is no sample called \"{id}\"."));
                var layout = LayoutLoader.FromFile(Samples.PathOf(sample.LayoutFile));
                var table = ControlTableExcel.Read(Samples.PathOf(sample.TablesFile));
                return TypedResults.Ok(CheckRunner.Run(layout, table, sample.TablesFile));
            })
            .WithSummary("Check a built-in sample layout against its example control tables");

        api.MapGet("/samples/{id}/files/{kind}", IResult (string id, string kind) =>
            {
                var sample = Samples.Find(id);
                if (sample is null)
                    return TypedResults.NotFound(new ProblemDetailsMessage($"There is no sample called \"{id}\"."));
                return kind.ToLowerInvariant() switch
                {
                    "layout" => TypedResults.PhysicalFile(Samples.PathOf(sample.LayoutFile), "application/json", sample.LayoutFile),
                    "tables" => TypedResults.PhysicalFile(Samples.PathOf(sample.TablesFile), XlsxType, sample.TablesFile),
                    _ => TypedResults.NotFound(new ProblemDetailsMessage("Use \"layout\" or \"tables\".")),
                };
            })
            .WithSummary("Download a sample's layout (JSON) or control tables (Excel)");

        api.MapPost("/check", async Task<Results<Ok<CheckResult>, BadRequest<ProblemDetailsMessage>>> (IFormFile layout, IFormFile? tables) =>
            {
                var input = await ReadInputs(layout, tables);
                if (input.Error is not null)
                    return TypedResults.BadRequest(input.Error);
                return TypedResults.Ok(CheckRunner.Run(input.Layout!, input.Table, tables?.FileName));
            })
            .DisableAntiforgery()
            .WithSummary("Check an uploaded layout (JSON), and optionally its control tables (Excel)");

        api.MapPost("/check/report", async Task<IResult> (IFormFile layout, IFormFile tables) =>
            {
                var input = await ReadInputs(layout, tables);
                if (input.Error is not null)
                    return TypedResults.BadRequest(input.Error);
                var issues = LayoutValidator.Validate(input.Layout!);
                if (issues.Count > 0)
                    return TypedResults.BadRequest(new ProblemDetailsMessage($"The layout has {issues.Count} problem(s); fix them before making a report."));

                var findings = RuleEngine.Run(input.Layout!, input.Table!);
                var bytes = WriteToBytes(path => FindingsReport.Write(path, input.Layout!, findings, RouteFinder.Derive(input.Layout!), DateTimeOffset.UtcNow));
                return TypedResults.File(bytes, XlsxType, "signalsafe-findings.xlsx");
            })
            .DisableAntiforgery()
            .WithSummary("Check an uploaded layout and control tables, and download the findings as Excel");

        api.MapPost("/draft", async Task<IResult> (IFormFile layout) =>
            {
                var input = await ReadInputs(layout, null);
                if (input.Error is not null)
                    return TypedResults.BadRequest(input.Error);
                var issues = LayoutValidator.Validate(input.Layout!);
                if (issues.Count > 0)
                    return TypedResults.BadRequest(new ProblemDetailsMessage($"The layout has {issues.Count} problem(s); fix them before drafting tables."));

                var rows = ControlTableBuilder.Draft(input.Layout!);
                var bytes = WriteToBytes(path => ControlTableExcel.Write(path, rows, $"Draft control tables for {input.Layout!.Name}, generated by SignalSafe. Review before use."));
                return TypedResults.File(bytes, XlsxType, "draft-control-tables.xlsx");
            })
            .DisableAntiforgery()
            .WithSummary("Draft control tables (Excel) from an uploaded layout");

        api.MapGet("/templates/control-tables", () =>
                TypedResults.File(WriteToBytes(path => ControlTableExcel.Write(path, [])), XlsxType, "control-table-template.xlsx"))
            .WithSummary("Download a blank control table template");
    }

    private sealed record Inputs(Layout? Layout, ControlTable? Table, ProblemDetailsMessage? Error);

    private static async Task<Inputs> ReadInputs(IFormFile layoutFile, IFormFile? tablesFile)
    {
        if (layoutFile.Length == 0)
            return new(null, null, new("The layout file is empty."));
        if (layoutFile.Length > MaxLayoutBytes)
            return new(null, null, new($"The layout file is larger than {MaxLayoutBytes / 1024 / 1024} MB."));
        if (!layoutFile.FileName.EndsWith(".json", StringComparison.OrdinalIgnoreCase))
            return new(null, null, new("The layout must be a .json file."));

        Layout layout;
        using (var reader = new StreamReader(layoutFile.OpenReadStream()))
        {
            try
            {
                layout = LayoutLoader.FromJson(await reader.ReadToEndAsync());
            }
            catch (LayoutFormatException ex)
            {
                return new(null, null, new(ex.Message));
            }
        }

        if (tablesFile is null)
            return new(layout, null, null);
        if (tablesFile.Length > MaxTablesBytes)
            return new(null, null, new($"The control tables file is larger than {MaxTablesBytes / 1024 / 1024} MB."));
        if (!tablesFile.FileName.EndsWith(".xlsx", StringComparison.OrdinalIgnoreCase))
            return new(null, null, new("The control tables must be an Excel .xlsx file."));

        // ClosedXML needs a seekable stream; uploads are small, so buffer in memory.
        using var buffer = new MemoryStream();
        await tablesFile.CopyToAsync(buffer);
        buffer.Position = 0;
        return new(layout, ControlTableExcel.Read(buffer), null);
    }

    private static byte[] WriteToBytes(Action<string> write)
    {
        var path = Path.Combine(Path.GetTempPath(), $"signalsafe-{Guid.NewGuid():N}.xlsx");
        try
        {
            write(path);
            return File.ReadAllBytes(path);
        }
        finally
        {
            File.Delete(path);
        }
    }
}

/// <summary>A plain error message the web app can show as it is.</summary>
public sealed record ProblemDetailsMessage(string Error);
